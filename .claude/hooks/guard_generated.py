#!/usr/bin/env python3
"""
PreToolUse hook — blocks edits to auto-generated files and compiled dist artifacts.

Two categories are blocked:
1. Files with "Auto-generated by langue. Do not edit." in the first line —
   regenerate via scripts/gen_langue.sh after fixing the Lumo source.
2. Files under packages/*/dist/ — compiled output of Lumo packages;
   edit the Lumo source under packages/*/src/ and rebuild with lbs.
"""

import json
import os
import sys

GENERATED_MARKER = "Auto-generated by langue. Do not edit."


def is_generated_file(path: str) -> bool:
    try:
        with open(path, "r", encoding="utf-8") as f:
            first_line = f.readline()
        return GENERATED_MARKER in first_line
    except (OSError, UnicodeDecodeError):
        return False


def is_dist_artifact(path: str) -> bool:
    """True when the path is inside a packages/*/dist/ directory."""
    parts = path.replace("\\", "/").split("/")
    for i in range(len(parts) - 2):
        if parts[i] == "packages" and i + 2 < len(parts) and parts[i + 2] == "dist":
            return True
    return False


def main():
    try:
        data = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        sys.exit(0)

    tool_name = data.get("tool_name", "")
    tool_input = data.get("tool_input", {})

    if tool_name not in ("Edit", "Write", "NotebookEdit"):
        sys.exit(0)

    file_path = tool_input.get("file_path", "")
    if not file_path:
        sys.exit(0)

    # Block edits to compiled dist artifacts (packages/*/dist/*)
    if is_dist_artifact(file_path):
        pkg = file_path.replace("\\", "/").split("/dist/")[0].split("/")[-1]
        print(
            f"Blocked: {file_path} is a compiled dist artifact. "
            f"Edit the Lumo source under packages/{pkg}/src/ and rebuild with "
            f"`cargo run -p lbs -- build --target js packages/{pkg}`."
        )
        sys.exit(2)

    # For Write: check the content being written rather than the on-disk file
    if tool_name == "Write":
        content = tool_input.get("content", "")
        if GENERATED_MARKER in content.split("\n")[0]:
            print(
                f"Blocked: {file_path} appears to be auto-generated. "
                "Edit the Lumo source and run scripts/gen_langue.sh instead of "
                "writing the file directly."
            )
            sys.exit(2)
        sys.exit(0)

    # For Edit: check the existing file on disk
    if is_generated_file(file_path):
        print(
            f"Blocked: {file_path} is auto-generated by langue. "
            "Edit the Lumo source and run scripts/gen_langue.sh instead of "
            "editing directly."
        )
        sys.exit(2)

    sys.exit(0)


if __name__ == "__main__":
    main()
